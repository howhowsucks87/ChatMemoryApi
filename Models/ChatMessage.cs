namespace ChatMemoryApi.Models
{
    // ==========================================================
    // ChatMessage
    // ----------------------------------------------------------
    // 功能：
    // 儲存使用者的聊天訊息
    // 與 User 建立關聯（多對一）
    // 作為對話紀錄資料表
    //
    // 在資料庫中會對應為：
    // Table: ChatMessages
    //
    // 關聯關係：
    // 一個 User 可以有 多個 ChatMessage
    // 一個 ChatMessage 只屬於 一個 User
    // ==========================================================
    public class ChatMessage
    {
        // ----------------------------------------------------------
        // 主鍵（Primary Key）
        // ----------------------------------------------------------
        public int Id { get; set; }


        // ----------------------------------------------------------
        // 外鍵（Foreign Key）
        // ----------------------------------------------------------
        // 指向 User.Id
        public int UserId { get; set; }


        // ----------------------------------------------------------
        // 訊息內容
        // ----------------------------------------------------------
        public string Content { get; set; } = null!;


        // ----------------------------------------------------------
        // 建立時間（UTC）
        // ----------------------------------------------------------
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;


        // ----------------------------------------------------------
        // 導覽屬性（Navigation Property）
        // ----------------------------------------------------------
        // 代表關聯的 User 物件
        public User User { get; set; } = null!;
    }
}