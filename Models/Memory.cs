namespace ChatMemoryApi.Models
{
    // ==========================================================
    // Memory
    // ----------------------------------------------------------
    // 功能：
    // 儲存使用者的「長期記憶」或對話摘要
    // 可用於 RAG（Retrieval-Augmented Generation）
    // 用來減少模型上下文長度限制問題
    //
    // 在資料庫中對應：
    // Table: Memories
    //
    // 關聯關係：
    // 一個 User 可以擁有多個 Memory
    // 一個 Memory 只屬於一個 User
    // ==========================================================
    public class Memory
    {
        // ----------------------------------------------------------
        // 主鍵（Primary Key）
        // ----------------------------------------------------------
        public int Id { get; set; }


        // ----------------------------------------------------------
        // 外鍵（Foreign Key）
        // ----------------------------------------------------------
        // 指向 User.Id
        public int UserId { get; set; }


        // ----------------------------------------------------------
        // Summary（摘要內容）
        // ----------------------------------------------------------
        // 儲存 AI 產生的對話摘要或長期記憶內容
        //
        // 可能包含：
        // - 使用者偏好
        // - 對話重點
        // - 任務紀錄
        public string Summary { get; set; } = null!;


        // ----------------------------------------------------------
        // 建立時間（UTC）
        // ----------------------------------------------------------
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;


        // ----------------------------------------------------------
        // 導覽屬性（Navigation Property）
        // ----------------------------------------------------------
        // 代表關聯的 User 物件
        public User User { get; set; } = null!;
    }
}